// MAX TIME v48 — точечное дополнение программы среды.
// Отдельный патч сохраняет неизменными существующие ID упражнений и историю тренировок.
(function(){
  if(typeof P==='undefined'||!P[3]||!Array.isArray(P[3].ex))return;
  if(P[3].ex.some(ex=>ex.id==='uprightband'))return;
  const exercise={
    id:'uprightband',
    n:'Вертикальная тяга резинки стоя',
    s:2,min:10,max:15,r:2,rest:60,band:true,
    h:'Основная: средняя дельта. Дополнительно: верх трапеции и передняя дельта. Тяни локтями вверх примерно до уровня верхней части груди; не нужно поднимать кисти к самому подбородку и чрезмерно задирать локти выше плеч.',
    v:YT('вертикальная тяга резинки стоя на среднюю дельту техника')
  };
  const after=P[3].ex.findIndex(ex=>ex.id==='lateral');
  P[3].ex.splice(after>=0?after+1:1,0,exercise);
})();